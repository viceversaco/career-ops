export const meta = {
  name: 'career-ops-pipeline',
  description: 'Parallel fan-out for /career-ops pipeline: one worker per pending URL evaluates the offer (A-G) and writes report.md + tracker TSV (NO PDF), then a single agent merges tracker-additions into applications.md and verifies pipeline integrity. Replaces the sequential/foreground Agent spawning in modes/pipeline.md.',
  phases: [
    { title: 'Evaluate', detail: 'one crawl4ai-extracting worker per pending URL (parallel, no Playwright, no PDF)' },
    { title: 'Merge', detail: 'merge-tracker.mjs + verify-pipeline.mjs in a single Bash agent' },
  ],
}

// ---------------------------------------------------------------------------
// Sandbox note: this script body runs WITHOUT filesystem/Node APIs, and
// Date.now()/Math.random()/new Date() THROW. All nondeterminism (date, ids,
// baseNum) is supplied by the caller via `args`; slugs are generated by the
// worker agents (which have full tools). Do not add new Date()/Math.random().
// ---------------------------------------------------------------------------

const EVAL_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  properties: {
    status: { type: 'string', enum: ['completed', 'failed'] },
    id: { type: 'string' },
    report_num: { type: 'string', description: 'zero-padded 3-digit, e.g. "014"' },
    company: { type: 'string' },
    role: { type: 'string' },
    score: { type: ['number', 'null'], description: 'numeric only, no /5; null on failure' },
    legitimacy: {
      type: ['string', 'null'],
      enum: ['High Confidence', 'Proceed with Caution', 'Suspicious', null],
    },
    pdf: { type: 'null', description: 'ALWAYS null — PDF is disabled on this path' },
    report: { type: ['string', 'null'], description: 'path to reports/{num}-{slug}-{date}.md, or null' },
    final_decision: {
      type: ['string', 'null'],
      enum: ['Apply', 'Consider', 'Research first', 'Skip', null],
      description: 'from the report Machine Summary; drives the Recommended action column',
    },
    error: { type: ['string', 'null'] },
  },
  required: ['status', 'id', 'report_num', 'company', 'role', 'score', 'legitimacy', 'pdf', 'report', 'final_decision', 'error'],
}

// The Workflow runtime delivers `args` as a JSON string in some harnesses and as
// a plain object in others — normalize so this script works under both.
const _input = typeof args === 'string' ? JSON.parse(args) : (args || {})
const { date, baseNum, careerOpsDir, offers } = _input

const pad3 = (n) => String(n).padStart(3, '0')

// id -> url lookup so failure records returned to the caller carry the URL
// the main-loop Playwright mop-up needs.
const urlById = {}
for (const o of offers) urlById[o.id] = o.url

// Build the self-contained worker prompt for one offer with a FIXED report number.
const workerPrompt = (offer, reportNum) => {
  const num = pad3(reportNum)
  const jdBlock = offer.jd
    ? [
        'JD text is PROVIDED inline below — use it directly, do NOT fetch anything:',
        '<<<JD',
        String(offer.jd),
        'JD>>>',
      ].join('\n')
    : [
        'No JD provided. Extract it yourself, parallel-safe, in THIS order ONLY:',
        '  1. Bash: crawl4ai "' + offer.url + '"   (headless-browser-backed, per-process. It auto-applies',
        '     the matching site profile — cookies, schema.org/JobPosting JSON-LD recovery, and URL',
        '     rewrites — so LinkedIn, Ashby SPAs, and Greenhouse embeds usually extract cleanly here.)',
        '  2. Inspect the output and branch:',
        '     - LOGIN WALL: if it contains "returned a login wall" and "crawl4ai-cookies import", the',
        '       site session cookie is missing/expired. STOP. Return status:"failed" with',
        '       error:"cookies-expired: <site>", where <site> is the word right after "[crawl4ai]" in that',
        '       message (e.g. error:"cookies-expired: linkedin"). Write NO report/TSV. Do NOT retry — a',
        '       browser would hit the same wall; the user must refresh the cookie.',
        '     - THIN/ERROR: if empty, an error, or obviously not a JD: STOP. Return status:"failed" with',
        '       error:"extraction-failed: ' + offer.url + '". Write NO report/TSV.',
        '     - OTHERWISE it is the JD (markdown or recovered JSON-LD) — proceed to STEP B.',
        '  Do NOT use Playwright/browser_* tools (project rule modes/_shared.md: never 2+ parallel Playwright).',
        '  Do NOT use WebFetch (disabled).',
      ].join('\n')

  return [
    'You are a career-ops batch evaluation worker. Project root: ' + careerOpsDir + ' (use ABSOLUTE paths).',
    '',
    'READ FIRST (your spec + scoring rules):',
    '  1. ' + careerOpsDir + '/modes/_shared.md          — scoring system, archetypes, canonical statuses, global rules',
    '  2. ' + careerOpsDir + '/batch/batch-prompt.md      — YOUR EXECUTION SPEC. Follow it step by step.',
    '  Also load (if present) ' + careerOpsDir + '/modes/_profile.md and ' + careerOpsDir + '/config/profile.yml',
    '  — user scoring overrides win over _shared.md defaults.',
    '  3. ' + careerOpsDir + '/cv.md and (if present) ' + careerOpsDir + '/article-digest.md',
    '     — the proof you score Block B against. article-digest.md OUTRANKS cv.md for project/metric claims;',
    '     honor its Measured/Estimated/Anecdotal metric tiering and never-fake list in ANY text you draft.',
    '',
    'Follow batch-prompt.md as your spec WITH THESE BINDING OVERRIDES:',
    '  - SKIP "Paso 4 — Generar PDF" ENTIRELY. Do NOT launch Playwright or generate-pdf.mjs.',
    '    In the report header use: **PDF:** not generated — run /career-ops pdf {company-slug} to create on demand',
    '    In the TSV (col 7) set pdf_emoji = ❌. In the returned JSON set "pdf": null.',
    '  - Your report number is FIXED: ' + num + '. Use exactly "' + num + '" everywhere {{REPORT_NUM}} appears.',
    '    Do NOT read reports/ to compute max+1 (the orchestrator assigned numbers deterministically).',
    '  - Do NOT use Playwright/browser_* tools anywhere.',
    '',
    'Placeholder bindings:',
    '  {{ID}}         = ' + offer.id,
    '  {{URL}}        = ' + offer.url,
    '  {{DATE}}       = ' + date,
    '  {{REPORT_NUM}} = ' + num,
    '  Company hint   = ' + (offer.company ? offer.company : '(none — derive from JD)'),
    '  Role hint      = ' + (offer.role ? offer.role : '(none — derive from JD)'),
    '',
    'STEP A — Obtain the JD (replaces batch-prompt.md "Paso 1"):',
    jdBlock,
    '',
    'STEP B — Evaluation A-G + report + TSV (batch-prompt.md Paso 2, 3, 5):',
    '  - Run the full A-G evaluation, applying _profile.md / profile.yml overrides.',
    '  - Write the report to ' + careerOpsDir + '/reports/' + num + '-{company-slug}-' + date + '.md',
    '    Header MUST include: **URL:** ' + offer.url + ' , **Legitimacy:** {tier}, and a ## Machine Summary YAML fence.',
    '  - Write the 9-column TSV line (status BEFORE score; tabs between columns) to:',
    '    ' + careerOpsDir + '/batch/tracker-additions/' + offer.id + '.tsv',
    '    Columns: ' + num + ' <tab> ' + date + ' <tab> {company} <tab> {role} <tab> {canonical_status} <tab> {score}/5 <tab> ❌ <tab> [' + num + '](reports/' + num + '-{company-slug}-' + date + '.md) <tab> {one-sentence note}',
    '    Status MUST be canonical (templates/states.yml): Evaluated | Applied | Responded | Interview | Offer | Rejected | Discarded | SKIP.',
    '    Use "Evaluated" for a fresh evaluation (or "SKIP" if final_decision is Skip).',
    '',
    'STEP C — Return the result object matching the schema (batch-prompt.md Paso 6).',
    '  "pdf" MUST be null. "final_decision" comes from your Machine Summary (Apply/Consider/Research first/Skip).',
    '  "score" is numeric only (no /5). On any failure set status:"failed" and explain in "error".',
  ].join('\n')
}

// ============ PHASE 1: EVALUATE (parallel fan-out) ============
phase('Evaluate')
log('Evaluating ' + offers.length + ' offer(s) in parallel (crawl4ai extraction, no Playwright, no PDF). baseNum=' + baseNum + '.')

const results = await parallel(
  offers.map((offer, i) => () => {
    const reportNum = baseNum + i
    return agent(workerPrompt(offer, reportNum), {
      schema: EVAL_SCHEMA,
      label: 'eval:' + offer.id,
      phase: 'Evaluate',
      // Model + reasoning effort are pinned on the career-ops-evaluator subagent
      // definition (.claude/agents/career-ops-evaluator.md): model opus, effort
      // high. The Workflow agent() API has no inline effort option (CC #43083),
      // so per-stage effort must be routed through a named subagent.
      agentType: 'career-ops-evaluator',
    })
      .then((r) => r || null)
      .catch((e) => ({
        status: 'failed',
        id: offer.id,
        report_num: pad3(reportNum),
        company: offer.company || 'unknown',
        role: offer.role || 'unknown',
        score: null,
        legitimacy: null,
        pdf: null,
        report: null,
        final_decision: null,
        error: 'worker crashed: ' + (e && e.message ? e.message : 'unknown'),
      }))
  })
)

const completed = results.filter((r) => r && r.status === 'completed')
const failed = results.filter((r) => r && r.status === 'failed')
const cookieFailures = failed.filter((r) => /cookies-expired/i.test(r.error || ''))
const extractionFailures = failed.filter((r) => /extraction-failed/i.test(r.error || ''))
const otherFailures = failed.filter((r) => !/cookies-expired|extraction-failed/i.test(r.error || ''))
log('Evaluate done: ' + completed.length + ' completed, ' + cookieFailures.length + ' cookie-expired, ' + extractionFailures.length + ' need extraction mop-up, ' + otherFailures.length + ' other failures.')

// Parse the site name out of a "cookies-expired: <site>" error.
const siteOf = (err) => (String(err || '').match(/cookies-expired:\s*(\S+)/i) || [])[1] || 'unknown'

// ============ PHASE 2: MERGE (single agent — needs Bash) ============
phase('Merge')

let merge = { merged: false, verifyClean: false, verifyErrors: ['merge skipped — no completed evaluations'], mergeSummary: '' }

if (completed.length > 0) {
  const MERGE_SCHEMA = {
    type: 'object',
    additionalProperties: false,
    properties: {
      merged: { type: 'boolean' },
      verifyClean: { type: 'boolean', description: 'true if verify-pipeline.mjs exited 0 (green/yellow)' },
      verifyErrors: { type: 'array', items: { type: 'string' } },
      mergeSummary: { type: 'string' },
    },
    required: ['merged', 'verifyClean', 'verifyErrors', 'mergeSummary'],
  }

  const mergePrompt = [
    'Project root: ' + careerOpsDir + '. Worker agents just wrote TSV files to batch/tracker-additions/.',
    'Run these two commands with Bash, from ' + careerOpsDir + ', in order:',
    '  1. node ' + careerOpsDir + '/merge-tracker.mjs',
    '  2. node ' + careerOpsDir + '/verify-pipeline.mjs',
    'merge-tracker.mjs is idempotent (dedups company+role, swaps status/score columns, normalizes report links,',
    'moves consumed TSVs to tracker-additions/merged/). verify-pipeline.mjs exits non-zero on errors.',
    'Report: merged (did merge-tracker run cleanly?), verifyClean (did verify exit 0?),',
    'verifyErrors (any ❌ lines from verify — broken links, non-canonical statuses), and mergeSummary (the summary line).',
    'Do NOT edit applications.md by hand. Do NOT re-run any worker.',
  ].join('\n')

  // Model + effort pinned on .claude/agents/career-ops-merger.md: model sonnet, effort medium.
  merge = await agent(mergePrompt, { schema: MERGE_SCHEMA, label: 'merge+verify', phase: 'Merge', agentType: 'career-ops-merger' })
    .catch((e) => ({ merged: false, verifyClean: false, verifyErrors: ['merge agent crashed: ' + (e && e.message)], mergeSummary: '' }))
} else {
  log('No completed evaluations — skipping merge.')
}

// ============ RETURN: summary for the caller (main loop) ============
return {
  date,
  baseNum,
  counts: { total: offers.length, completed: completed.length, cookieExpired: cookieFailures.length, extractionFailed: extractionFailures.length, otherFailed: otherFailures.length },
  merge,
  // Move these Pending -> Processed in data/pipeline.md and print the summary table:
  processed: completed.map((r) => ({
    id: r.id,
    reportNum: r.report_num,
    company: r.company,
    role: r.role,
    score: r.score,
    legitimacy: r.legitimacy,
    recommendedAction: r.final_decision,
    report: r.report,
    pdf: false,
  })),
  // Cookie expired/missing — do NOT Playwright (same wall). Ask the user to run
  // `crawl4ai-cookies import <site>`, then re-run pipeline for these.
  cookieFailures: cookieFailures.map((r) => ({ id: r.id, url: urlById[r.id], company: r.company, role: r.role, site: siteOf(r.error) })),
  // Main loop: sequential Playwright last-resort for these, then manual paste:
  extractionFailures: extractionFailures.map((r) => ({ id: r.id, url: urlById[r.id], company: r.company, role: r.role })),
  // Surface, but do not retry automatically:
  otherFailures: otherFailures.map((r) => ({ id: r.id, url: urlById[r.id], company: r.company, role: r.role, reportNum: r.report_num, error: r.error })),
}
